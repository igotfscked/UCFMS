"""Write copybooks/UCFNUMI.cpy, the NUMIDENT KSDS record, from the field
layouts in ucfms/numident.py (one source for the Python loader and COBOL).

    python3 numident_layout.py

Stored record (HLQ.NUMI.KSDS, built by jcl/UCFNLOAD.jcl), 556 bytes:
    1- 20  key: NH last name   (NARA cols 69-88)
   21- 35  key: NH first name  (NARA cols 37-51)
   36- 44  key: SSN            (NARA cols 13-21)
   45      key: record kind    D death, C claim, S SS-5
   46- 56  key: reference number (NARA cols 1-11)
   57-556  the NARA 500-column record, unchanged (NARA column + 56)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))

from ucfms.numident import DEATH_GROUP, DEATH_OCCURS, LAYOUTS  # noqa: E402

KEY = [("NU-KEY-LAST", 20), ("NU-KEY-FIRST", 15), ("NU-KEY-SSN", 9),
       ("NU-KEY-KIND", 1), ("NU-KEY-REF", 11)]
KEY_LEN = sum(n for _, n in KEY)  # 56


def cob(name, kind):
    return name.replace("NUMI-", f"NU-{kind}-", 1)


def pic(n):
    return f"PIC X({n})."


def line(level, name, clause=""):
    """01 in area A (column 8), then 4 columns deeper per level, like UCFCTL."""
    depth = {1: 0, 5: 4, 10: 8, 15: 12}[level]
    s = f"{' ' * (7 + depth)}{level:02d}  {name}"
    if clause:
        s = f"{s:<48} {clause}"
    assert len(s) <= 72, s
    return s


def body(kind, fields, lo, hi, level):
    """Fields between columns lo..hi in order, gaps as FILLER."""
    out, pos = [], lo
    for name, start, n in sorted(fields, key=lambda f: f[1]):
        if start < lo or start > hi:
            continue
        if start > pos:
            out.append(line(level, "FILLER", pic(start - pos)))
        out.append(line(level, cob(name, kind), pic(n)))
        pos = start + n
    if pos <= hi:
        out.append(line(level, "FILLER", pic(hi - pos + 1)))
    return out


def copybook():
    out = [
        "      *----------------------------------------------------------*",
        "      * UCFNUMI  NUMIDENT RECORD        HLQ.NUMI.KSDS            *",
        "      * RECORD LENGTH 556 = KEY 56 + NARA RECORD 500             *",
        "      * KEYS(56 0)  AIX ON SSN: KEYS(9 68) = NARA COLS 13-21     *",
        "      * GENERATED BY DESIGN/NUMIDENT_LAYOUT.PY - DO NOT EDIT     *",
        "      * NARA DATES: DOB/DOD/CLAIM MMDDCCYY, CYCLE/POSTING        *",
        "      * CCYYMMDD; UNKNOWN PARTS ARE 00 OR XX.                    *",
        "      *----------------------------------------------------------*",
        line(1, "NU-RECORD."),
        line(5, "NU-KEY."),
    ]
    out += [line(10, n, pic(w)) for n, w in KEY]
    out.append(line(5, "NU-NARA", pic(500)))
    for kind, title in (("D", "DEATH"), ("C", "CLAIM"), ("S", "SS-5")):
        out.append(f"      * {title} RECORD (NU-KEY-KIND = '{kind}')")
        out.append(line(5, f"NU-{kind}-REC REDEFINES NU-NARA."))
        fields = LAYOUTS[kind]
        if kind == "D":
            lo, hi = DEATH_GROUP
            out += body(kind, fields, 1, lo - 1, 10)
            out.append("      * DEATH POSTINGS: NU-D-NOE OF THEM (NARA COPIES HOLD 1)")
            out.append(line(10, "NU-D-POSTING OCCURS 3 TIMES."))
            out += body(kind, fields, lo, hi, 15)
            rest = [f for f in fields if f[1] > hi]
            out += body(kind, rest, lo + 3 * DEATH_OCCURS, 500, 10)
        else:
            out += body(kind, fields, 1, 500, 10)
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    p = os.path.join(HERE, "copybooks", "UCFNUMI.cpy")
    open(p, "w").write(copybook())
    print("wrote", p)
